import { z } from 'zod';

export const loginSchema = z.object({
  email: z.string().email(),
  password: z.string().min(8),
});

export const registerSchema = z.object({
  email: z.string().email(),
  password: z.string().min(8),
  name: z.string().min(1),
  orgName: z.string().min(1),
});

export const authContextSchema = z.object({
  userId: z.string(),
  orgId: z.string(),
  roles: z.array(z.string()),
});
